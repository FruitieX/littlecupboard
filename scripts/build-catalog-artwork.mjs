// Explicitly reviewed product→artwork assignments; no category/cart fallbacks.
import assert from 'node:assert/strict'
import { readFile, writeFile, access } from 'node:fs/promises'
import { format, resolveConfig } from 'prettier'

const batches = JSON.parse(
  await readFile('docs/artwork/catalog-batches.json', 'utf8'),
)
const vectors = JSON.parse(
  await readFile('docs/artwork/catalog-vectors.json', 'utf8'),
)
const artworkAliases = JSON.parse(
  await readFile('docs/artwork/catalog-aliases.json', 'utf8'),
)
const artwork = {}
const id = (name) =>
  name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
function assign(name, path) {
  assert.ok(!artwork[id(name)], `Duplicate artwork assignment for ${name}`)
  artwork[id(name)] = path
}
for (const [emoji, names] of Object.entries(vectors)) {
  const code = [...emoji]
    .map((c) => c.codePointAt(0).toString(16))
    .filter((c) => c !== 'fe0f')
    .join('-')
  for (const name of names.split('|')) assign(name, `/images/food/${code}.svg`)
}
for (const batch of batches)
  for (const [key, , names] of batch)
    if (names)
      for (const name of names.split('|'))
        assign(name, `/images/catalog/generated/${key}.webp`)
for (const path of new Set(Object.values(artwork)))
  await access(`public${path}`)
for (const path of new Set(Object.values(artworkAliases)))
  await access(`public${path}`)
await writeFile(
  'src/lib/catalog-artwork.ts',
  await format(
    '// Generated by scripts/build-catalog-artwork.mjs from the reviewed artwork manifests.\nexport const catalogArtwork: Record<string, string> = ' +
      JSON.stringify(artwork, null, 2) +
      '\nexport const catalogArtworkAliases: Record<string, string> = ' +
      JSON.stringify(artworkAliases, null, 2) +
      '\n' +
      `export function defaultCatalogImage(id: string, name?: string, icon?: string) {\n return catalogArtwork[id] ?? ((!icon || icon.trim() === '🛒') && name ? Object.entries(catalogArtworkAliases).find(([alias]) => alias.toLowerCase() === name.trim().toLowerCase())?.[1] : undefined)\n}\n`,
    {
      ...(await resolveConfig('src/lib/catalog-artwork.ts')),
      parser: 'typescript',
    },
  ),
)
console.log(
  `Assigned ${Object.keys(artwork).length} products to ${new Set(Object.values(artwork)).size} reviewed icons.`,
)
