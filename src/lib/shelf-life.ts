/**
 * Effective shelf life: a household setting wins (0 turns a default off),
 * otherwise the built-in default, otherwise none.
 */
export function shelfLifeDays(state: AppState, id: string) {
  const override = state.shelfLifeDays?.[id]
  if (override !== undefined) return override > 0 ? override : undefined
  return defaultShelfLifeDays[id]
}
